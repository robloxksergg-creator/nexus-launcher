"""Installer view only. Download, verification and UAC stay in their owners."""
from PySide6.QtWidgets import (QHBoxLayout, QLabel, QLineEdit, QProgressBar,
                              QPushButton, QScrollArea, QVBoxLayout, QWidget)
from .installer_location import default_directory
from .nexus_platform.workspace_visuals import BrandSurface, panel, workspace_style
from .nexus_platform.presentation_style import stylesheet


def build_installer(window, beta):
    window.setMinimumSize(620, 600)
    window.setMaximumWidth(1040)
    window.resize(920, 780)
    window.setStyleSheet(stylesheet() + workspace_style())
    outer = QVBoxLayout(window)
    outer.setContentsMargins(0, 0, 0, 0)
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setFrameShape(QScrollArea.NoFrame)
    surface = BrandSurface()
    layout = QVBoxLayout(surface)
    layout.setContentsMargins(32, 28, 32, 28)
    layout.setSpacing(22)
    kicker = QLabel('NEXUS / TESTERS · BETA' if beta else 'NEXUS / INSTALL')
    kicker.setObjectName('workspaceKicker')
    layout.addWidget(kicker)
    title = QLabel('Твой следующий мир.\nНачнём с установки.')
    title.setObjectName('workspaceTitle')
    title.setWordWrap(True)
    layout.addWidget(title)
    lead = QLabel('Выбери папку — мы скачаем лаунчер, проверим подпись пакета и подготовим файлы.')
    lead.setWordWrap(True)
    lead.setStyleSheet('color:#cbdced;font-size:16px;')
    layout.addWidget(lead)
    destination, box = panel('Где будет жить NEXUS', 'По умолчанию — рядом с установщиком. Сборки и миры останутся в выбранной папке.')
    row = QHBoxLayout()
    window.path = QLineEdit(str(default_directory()))
    window.path.setAccessibleName('Папка установки')
    window.choose = QPushButton('Выбрать…')
    window.choose.clicked.connect(window.browse)
    row.addWidget(window.path, 1)
    row.addWidget(window.choose)
    box.addLayout(row)
    layout.addWidget(destination)
    progress, box = panel('Подготовка лаунчера')
    steps = QHBoxLayout()
    window.phase_labels = []
    for text in ('Выпуск', 'Скачивание', 'Проверка'):
        label = QLabel(text)
        label.setObjectName('muted')
        steps.addWidget(label)
        window.phase_labels.append(label)
    box.addLayout(steps)
    state = QHBoxLayout()
    window.status = QLabel('Готово к установке')
    window.status.setWordWrap(True)
    window.percent = QLabel('0%')
    window.percent.setAccessibleName('Процент установки')
    window.percent.setStyleSheet('color:#9bd9ff;font-size:19px;font-weight:650;')
    state.addWidget(window.status, 1)
    state.addWidget(window.percent)
    box.addLayout(state)
    window.bar = QProgressBar()
    window.bar.setTextVisible(False)
    window.bar.setRange(0, 100)
    window.bar.setValue(0)
    box.addWidget(window.bar)
    window.transfer_detail = QLabel('Скачивание начнётся после нажатия кнопки.')
    window.transfer_detail.setObjectName('muted')
    window.transfer_detail.setWordWrap(True)
    box.addWidget(window.transfer_detail)
    note = QLabel('Старые сборки не переносятся автоматически. Место на диске проверим перед загрузкой.\nEXE пока без подписи Windows: Smart App Control может ограничить запуск.\nЕсли папка защищена, отдельно предложим запрос Windows на её создание. Лаунчер работает без повышения прав.')
    note.setWordWrap(True)
    note.setStyleSheet('color:#a9bed4;font-size:12px;')
    layout.addWidget(note)
    layout.addStretch()
    scroll.setWidget(surface)
    outer.addWidget(scroll, 1)
    progress_wrap = QWidget()
    progress_box = QVBoxLayout(progress_wrap)
    progress_box.setContentsMargins(32, 10, 32, 10)
    progress_box.addWidget(progress)
    outer.addWidget(progress_wrap)
    footer = QWidget()
    footer.setObjectName('installFooter')
    footer.setStyleSheet('QWidget#installFooter {background:#0d1b2b;}')
    actions = QVBoxLayout(footer)
    actions.setContentsMargins(32, 16, 32, 18)
    window.go = QPushButton('Скачать и установить')
    window.go.setObjectName('primaryAction')
    window.go.setMinimumHeight(36)
    window.go.clicked.connect(window.start)
    actions.addWidget(window.go)
    window.open = QPushButton('Открыть папку установки')
    window.open.hide()
    window.open.clicked.connect(window.open_install_folder)
    actions.addWidget(window.open)
    window.launch = QPushButton('Запустить NEXUS')
    window.launch.hide()
    window.launch.clicked.connect(window.run_launcher)
    actions.addWidget(window.launch)
    legal = QHBoxLayout()
    copyright = QLabel('Икрам Ikram / ForceCore · GPL-3.0-only')
    copyright.setStyleSheet('color:#a9bed4;font-size:11px;')
    legal.addWidget(copyright, 1)
    window.licenses = QPushButton('Лицензии компонентов ↗')
    legal.addWidget(window.licenses)
    actions.addLayout(legal)
    outer.addWidget(footer)
