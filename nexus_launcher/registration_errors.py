def registration_error(error, action):
    status = getattr(error, "http_status", None)
    outcome = getattr(error, "outcome", None)
    # Losing a mutation response is not evidence that the mutation failed.
    uncertain = outcome in {"network_error", "protocol_error"} or (status is not None and status >= 500) or type(error).__name__ in {"TransportError", "OfflineError", "ProtocolError"}
    if action == "register" and uncertain:
        return "Ответ не подтверждён. Аккаунт мог быть создан: проверьте вход перед повтором."
    if action in {"profile", "availability"} and uncertain:
        return "Ответ не подтверждён. Аккаунт сохранён; повторная попытка сначала проверит игровой профиль."
    message = EXACT_ERRORS.get(str(error))
    if message:
        return message
    if status == 429:
        return "Слишком много попыток. Подождите и повторите запрос позже."
    if status == 401:
        return "Сессия истекла или отсутствует. Войдите снова."
    if status == 403:
        return "Запрос отклонён проверкой безопасности. Проверьте устройство и подключение."
    if status == 409:
        return "Данные уже используются или изменились. Проверьте вход и состояние профиля."
    if status == 502:
        return "Сервер не подтвердил отправку письма. Проверьте почту перед новым запросом."
    if status == 503:
        return "Сервис временно недоступен. Попробуйте позже."
    if status is not None and status >= 500:
        return "Ошибка сервера аккаунтов. Попробуйте позже."
    if outcome == "network_error":
        return "Нет подтверждённого соединения с сервером. Проверьте интернет и попробуйте позже."
    if outcome == "protocol_error":
        return "Сервер вернул некорректный ответ. Отправка кода не подтверждена."
    return "Запрос не выполнен. Проверьте введённые данные и попробуйте позже."
